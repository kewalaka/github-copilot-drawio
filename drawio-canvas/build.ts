import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const inputs = ['drawio-canvas/build.ts', 'drawio-canvas/runtime-entry.ts', 'drawio-canvas/install-assets.ts', 'diagram-bridge/server.ts', 'diagram-bridge/updates.ts', 'diagram-bridge/model.ts', 'diagram-bridge/empty.ts', 'diagram-bridge/shapes.ts', 'diagram-bridge/desktop.ts', 'diagram-bridge/public/index.html', 'diagram-bridge/public/style.css', 'diagram-bridge/public/app.js', 'diagram-bridge/package.json', 'diagram-bridge/bun.lock', 'drawio-canvas/THIRD_PARTY_NOTICES.txt'];
const sha256 = (data: string | Buffer) => createHash('sha256').update(data).digest('hex');

export async function buildRuntime({ write = false } = {}) {
  const pkg = JSON.parse(readFileSync(join(root, 'diagram-bridge/package.json'), 'utf8'));
  const dependency = JSON.parse(readFileSync(join(root, 'diagram-bridge/node_modules/@xmldom/xmldom/package.json'), 'utf8'));
  if (pkg.dependencies['@xmldom/xmldom'] !== '0.9.12' || dependency.version !== '0.9.12') throw new Error('Build requires the pinned @xmldom/xmldom 0.9.12 dependency. Run the frozen development install.');
  const result = await Bun.build({
    entrypoints: [join(root, 'drawio-canvas/runtime-entry.ts')],
    target: 'node', format: 'esm', minify: false,
    loader: { '.html': 'text', '.css': 'text' },
    plugins: [{ name: 'embedded-editor-script', setup(build) {
      build.onLoad({ filter: /[/\\]diagram-bridge[/\\]public[/\\]app\.js$/ }, args => ({ contents: `export default ${JSON.stringify(readFileSync(args.path, 'utf8'))};`, loader: 'js' }));
    } }],
  });
  if (!result.success || result.outputs.length !== 1) throw new Error(result.logs.join('\n') || 'Expected one Node runtime bundle.');
  const text = '// Generated by drawio-canvas/build.ts; do not edit. Bundles @xmldom/xmldom 0.9.12 (MIT); see THIRD_PARTY_NOTICES.txt.\n' + await result.outputs[0].text();
  if (/\bBun\.|(?:\/Users\/|\/home\/)[^\s"']+|[A-Z]:\\\\Users\\\\/.test(text)) throw new Error('Runtime contains a Bun dependency or a personal absolute path.');
  const metadata = { format: 1, target: 'node', dependency: '@xmldom/xmldom@0.9.12', runtimeSha256: sha256(text), sources: Object.fromEntries(inputs.map(path => [path, sha256(readFileSync(join(root, path)))])) };
  if (write) {
    writeFileSync(join(root, 'drawio-canvas/runtime.mjs'), text);
    writeFileSync(join(root, 'drawio-canvas/build-manifest.json'), JSON.stringify(metadata, null, 2) + '\n');
  }
  return { text, metadata };
}

if (import.meta.main) {
  await buildRuntime({ write: true });
  console.log('Built drawio-canvas/runtime.mjs for ordinary Node; no assets or node_modules copied.');
}
